"""Profile the flat table and write a report that a human reads.

The output is reports/01-data-profile.md, regenerated from scratch every
run. Nobody should ever hand-edit it. If a number in the report looks wrong,
you fix the code and re-run, which means the report and the data can never
drift apart.
"""

from __future__ import annotations

import unicodedata

import pandas as pd

from . import config as C


def script_of(text: str) -> str:
    """Rough writing system of a string, from its first few letters."""
    if not text:
        return "empty"
    names = []
    for ch in text:
        if not ch.isalpha():
            continue
        try:
            names.append(unicodedata.name(ch).split()[0])
        except ValueError:
            names.append("UNKNOWN")
        if len(names) >= 8:
            break
    if not names:
        return "no-letters"
    common = max(set(names), key=names.count)
    return {"LATIN": "Latin", "CYRILLIC": "Cyrillic", "ARABIC": "Arabic",
            "CJK": "CJK", "HANGUL": "Hangul", "GREEK": "Greek",
            "HEBREW": "Hebrew"}.get(common, common.title())


def _presence(df: pd.DataFrame, prop: str) -> dict[str, object]:
    left = df[f"left_{prop}"].map(len) > 0
    right = df[f"right_{prop}"].map(len) > 0
    both = left & right
    return {
        "field": prop,
        "left_has": int(left.sum()),
        "right_has": int(right.sum()),
        "both_have": int(both.sum()),
        "both_pct": round(100 * both.mean(), 1),
    }


def build_report(df: pd.DataFrame) -> str:
    n = len(df)
    lines: list[str] = []
    add = lines.append

    add("# Data profile")
    add("")
    add("Generated by `python scripts/02_profile.py`. Do not edit by hand.")
    add("")
    add(f"Source: `{C.RAW_PAIRS.name}`  ")
    add(f"Rows: **{n:,}**")
    add("")

    add("## Label balance")
    add("")
    counts = df["judgement"].value_counts(dropna=False)
    add("| judgement | rows | share |")
    add("| --- | ---: | ---: |")
    for label, count in counts.items():
        add(f"| {label} | {count:,} | {100 * count / n:.1f}% |")
    add("")
    add("These pairs already survived a blocking step, so positives dominate.")
    add("The real class imbalance lives in the blocking that happens before")
    add("this file. Our false-positive counts are not production alert rates.")
    add("")

    add("## Record types")
    add("")
    pair_type = df["left_schema"].fillna("?") + " / " + df["right_schema"].fillna("?")
    add("| left / right | rows | in scope |")
    add("| --- | ---: | :---: |")
    for label, count in pair_type.value_counts().head(10).items():
        left_schema = label.split(" / ")[0]
        mark = "yes" if left_schema in C.IN_SCOPE_SCHEMAS else "no"
        add(f"| {label} | {count:,} | {mark} |")
    add("")
    in_scope = df["left_schema"].isin(C.IN_SCOPE_SCHEMAS)
    add(f"In scope: **{int(in_scope.sum()):,}** rows "
        f"({100 * in_scope.mean():.1f}%). Dropped: {int((~in_scope).sum()):,}.")
    add("")

    scoped = df[in_scope]

    add("## Field presence, in-scope rows only")
    add("")
    add("Which features are even possible. A feature needs the field on")
    add("*both* sides to be computable for that pair.")
    add("")
    presence = pd.DataFrame([_presence(scoped, p) for p in C.LIST_PROPS])
    presence = presence.sort_values("both_have", ascending=False)
    add("| field | left has | right has | both have | both % |")
    add("| --- | ---: | ---: | ---: | ---: |")
    for _, row in presence.iterrows():
        add(f"| {row['field']} | {row['left_has']:,} | {row['right_has']:,} "
            f"| {row['both_have']:,} | {row['both_pct']}% |")
    add("")

    add("## Writing systems")
    add("")
    sample = scoped.sample(min(40_000, len(scoped)), random_state=C.RANDOM_SEED)
    left_script = sample["left_caption"].fillna("").map(script_of)
    right_script = sample["right_caption"].fillna("").map(script_of)
    mixed = (left_script != right_script)
    add(f"Sampled {len(sample):,} in-scope rows.")
    add("")
    add("| script | share of left names |")
    add("| --- | ---: |")
    for label, share in left_script.value_counts(normalize=True).head(6).items():
        add(f"| {label} | {100 * share:.1f}% |")
    add("")
    add(f"Pairs where the two sides use **different** writing systems: "
        f"**{100 * mixed.mean():.1f}%**. Those are the ones plain edit")
    add("distance cannot help with.")
    add("")

    add("## Name lengths and aliases")
    add("")
    name_len = scoped["left_caption"].fillna("").str.len()
    alias_count = scoped["left_name"].map(len)
    add(f"- Name length: median {name_len.median():.0f} characters, "
        f"p90 {name_len.quantile(0.9):.0f}, max {name_len.max():.0f}")
    add(f"- Names per entity: median {alias_count.median():.0f}, "
        f"p90 {alias_count.quantile(0.9):.0f}, max {alias_count.max():.0f}")
    add("")
    add("An entity carries several spellings of its own name. Comparing only")
    add("the primary caption throws that away; compare across alias lists.")
    add("")

    add("## Hard negatives")
    add("")
    add("Ten negative pairs, sampled at random. These are what the model has")
    add("to separate, and no string metric does it alone.")
    add("")
    negatives = scoped[scoped["judgement"] == "negative"].sample(
        10, random_state=C.RANDOM_SEED)
    add("| left | right |")
    add("| --- | --- |")
    for _, row in negatives.iterrows():
        left = str(row["left_caption"]).replace("|", "/")
        right = str(row["right_caption"]).replace("|", "/")
        add(f"| {left} | {right} |")
    add("")

    return "\n".join(lines)


def run() -> str:
    df = pd.read_parquet(C.PAIRS_FLAT)
    report = build_report(df)
    C.REPORTS.mkdir(parents=True, exist_ok=True)
    out = C.REPORTS / "01-data-profile.md"
    out.write_text(report, encoding="utf-8")

    scoped = df[df["left_schema"].isin(C.IN_SCOPE_SCHEMAS)].copy()
    scoped.to_parquet(C.PAIRS_SCOPED, index=False)
    return str(out)
